/**
 * Composes data/route-names.json — the spoken form of all 84 route labels.
 *
 *   node scripts/build-route-names.mjs [--check]
 *
 * WHY GENERATED RATHER THAN TYPED. 84 hand-written strings drift: one route
 * says "гучин тав" and its neighbour "гучин таван", and nobody notices because
 * nobody reads the file top to bottom. Composing from two small tables — letter
 * names and number words — means a reviewer checks ~40 entries instead of 84
 * strings, and a correction to a number fixes every route that uses it.
 *
 * The OUTPUT is still a plain reviewable JSON file, committed and editable by
 * hand. A native speaker who disagrees with one entry edits that entry; this
 * script is not run at build time and will not overwrite them silently
 * (--check reports drift instead).
 *
 * THE CONVENTION: letter names, then the number as words.
 *
 *   Ч:35  → "чэ гучин тав"
 *   М:1Б  → "эм нэг бэ"
 *   ШҮ:1  → "ша ү нэг"
 *
 * Three reasons for spelling the letters rather than expanding them:
 *
 *   1. It is the convention already in the project. data/number-words.json
 *      renders the stop `MSM` as "эм эс эм" — Mongolian letter names for a
 *      Latin acronym. Route prefixes get the same treatment.
 *   2. The prefix is load-bearing and must survive. Ten route numbers are
 *      ambiguous without it — `Ч:9` and `Д:9` are different buses, as are the
 *      four routes numbered 4 — so it cannot be dropped for brevity.
 *   3. We do not know what the prefixes stand for. `ШҮ`, `ЗҮ` and `АТ` are
 *      plausibly abbreviations (шөнийн үйлчилгээ / зуслангийн үйлчилгээ /
 *      авто­тээвэр), but NOTHING in the feed says so — every longName just
 *      repeats the code. Guessing an expansion and speaking it as fact is the
 *      kind of confident wrong answer this app must not produce. Letter names
 *      are honest about what we actually know.
 *
 * No digits and no punctuation reach the engine, which matters beyond
 * pronunciation: Chimege rejects digits outright with HTTP 400, and a colon in
 * `Ч:35` is not something any engine reads correctly.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const ROUTES = "public/transit/routes.json";
const OUT = "data/route-names.json";
const CHECK = process.argv.includes("--check");

/**
 * Mongolian names of the Cyrillic letters used in route prefixes and suffixes.
 * `М` is confirmed against the existing `MSM → "эм эс эм"` entry.
 */
const LETTER = {
  А: "а", Б: "бэ", Д: "дэ", З: "зэ", М: "эм",
  Т: "тэ", Х: "хэ", Ч: "чэ", Ш: "ша", Ү: "ү",
};

/** Standalone cardinals, matching the `_cardinals` block of number-words.json. */
const ONES = ["", "нэг", "хоёр", "гурав", "дөрөв", "тав", "зургаа", "долоо", "найм", "ес"];

/** Standalone tens — what you say when the number ends there. */
const TENS_ALONE = ["", "арав", "хорь", "гуч", "дөч", "тавь", "жар", "дал", "ная", "ер"];

/** Attributive tens — the form used when a unit follows: гучин тав, далан зургаа. */
const TENS_PREFIX = ["", "арван", "хорин", "гучин", "дөчин", "тавин", "жаран", "далан", "наян", "ерэн"];

function numberToWords(n) {
  if (n < 1 || n > 99) throw new Error(`route number out of range: ${n}`);
  if (n < 10) return ONES[n];
  const tens = Math.floor(n / 10);
  const unit = n % 10;
  return unit === 0 ? TENS_ALONE[tens] : `${TENS_PREFIX[tens]} ${ONES[unit]}`;
}

function letters(text) {
  const out = [];
  for (const ch of text.toUpperCase()) {
    const name = LETTER[ch];
    if (!name) throw new Error(`no letter name for ${JSON.stringify(ch)} in ${JSON.stringify(text)}`);
    out.push(name);
  }
  return out.join(" ");
}

/** `Ч:35` / `Ч-38` / `М:1Б` / `Ч:16а` → prefix, number, optional suffix letter. */
function parse(displayName) {
  const m = /^([^\d:\-]+)[:\-]?(\d+)([^\d:\-]*)$/u.exec(displayName.trim());
  if (!m) throw new Error(`cannot parse route label ${JSON.stringify(displayName)}`);
  return { prefix: m[1], number: Number(m[2]), suffix: m[3] };
}

export function spokenFor(displayName) {
  const { prefix, number, suffix } = parse(displayName);
  return [letters(prefix), numberToWords(number), suffix ? letters(suffix) : null]
    .filter(Boolean)
    .join(" ");
}

const routes = JSON.parse(readFileSync(ROUTES, "utf8"));

const README = [
  "Spoken Mongolian for every route label. Generated by scripts/build-route-names.mjs.",
  "",
  "STATUS: DRAFT — needs review by a native speaker before shipping.",
  "The composition is mechanical and consistent; the WORDING is what needs eyes.",
  "Edit any entry by hand — this file is committed and the build never rewrites it.",
  "Run `node scripts/build-route-names.mjs --check` to see where hand edits differ",
  "from what the generator would produce.",
  "",
  "CONVENTION: letter names, then the number in words. Ч:35 -> 'чэ гучин тав'.",
  "No digits and no punctuation, because Chimege rejects digits with HTTP 400 and",
  "no engine reads the colon in 'Ч:35' correctly.",
  "",
  "OPEN QUESTION for the reviewer: the multi-letter prefixes are spelled out as",
  "letters (ШҮ -> 'ша ү') because nothing in the feed says what they abbreviate —",
  "every longName merely repeats the code. If they are in fact шөнийн үйлчилгээ,",
  "зуслангийн үйлчилгээ and автотээвэр, saying the words would be friendlier, and",
  "these nine entries are the ones to change: ШҮ:1 ШҮ:2 ШҮ:4 ЗҮ:4 АТ:4 АТ:5.",
  "",
  "The single-letter prefixes carry meaning too and are NOT droppable: ten route",
  "numbers are ambiguous without them (Ч:9 and Д:9 are different buses; four",
  "separate routes are numbered 4).",
];

const table = {};
const errors = [];
for (const route of routes) {
  try {
    table[route.displayName] = spokenFor(route.displayName);
  } catch (e) {
    errors.push(e.message);
  }
}

if (errors.length) {
  console.error("FAILED:\n  " + errors.join("\n  "));
  process.exit(1);
}

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error(`${OUT} does not exist — run without --check to create it.`);
    process.exit(1);
  }
  const current = JSON.parse(readFileSync(OUT, "utf8"));
  const drift = [];
  for (const [label, generated] of Object.entries(table)) {
    const held = typeof current[label] === "string" ? current[label] : current[label]?.spokenName;
    if (held !== generated) drift.push(`  ${label}: file=${JSON.stringify(held)} generated=${JSON.stringify(generated)}`);
  }
  const missing = Object.keys(table).filter((k) => !(k in current));
  if (missing.length) console.log(`MISSING from ${OUT}: ${missing.join(", ")}`);
  console.log(drift.length ? `hand edits differ from generated:\n${drift.join("\n")}` : "no drift");
  process.exit(0);
}

writeFileSync(OUT, JSON.stringify({ _README: README, ...table }, null, 2) + "\n");
console.log(`wrote ${OUT} — ${Object.keys(table).length} routes`);
for (const [label, spoken] of Object.entries(table)) console.log(`  ${label.padEnd(8)} ${spoken}`);
