/**
 * Emits model/classes.txt — the vocabulary handed to YOLOE at export time.
 *
 *   npx tsx scripts/export-classes.ts
 *
 * phrases.ts is the single source of truth for class ORDER (an index into
 * DETECTION_CLASSES is the classId in the ONNX export), so the list is derived
 * from it rather than maintained twice. Editing classes.txt by hand will drift
 * it out of sync with the wav files and mislabel detections.
 *
 * Format, one class per line:
 *
 *   <id> = <prompt>
 *
 * `id` is the wav filename and the name baked into the ONNX metadata. `prompt`
 * is what MobileCLIP's text encoder actually sees. They differ on purpose —
 * see PROMPT_OVERRIDES.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { PHRASES } from "../lib/phrases";

const OUT = resolve(process.cwd(), "model/classes.txt");

/**
 * Prompts that beat the `en` gloss when fed to a CLIP text encoder.
 *
 * The gloss in phrases.ts is documentation for humans reading that file; it is
 * not written to be embedded. Three problems it has, fixed here:
 *
 *   - snake_case ids ("trash_can") tokenize badly
 *   - polysemy: bare "hole" spans everything from a buttonhole to a black hole,
 *     while "pothole" lands squarely on the thing underfoot
 *   - a gloss listing alternatives ("curb / railing") embeds as neither
 *
 * Anything not listed here uses its `en` gloss unchanged.
 */
const PROMPT_OVERRIDES: Record<string, string> = {
  // Polysemy: pin these to the street-level sense.
  hole: "pothole in the road",
  ice: "patch of ice on the ground",
  rock: "rock on the ground",
  // "curb / railing" is two prompts wearing one coat. Curb is the tripping
  // hazard the wav actually warns about, so it wins.
  curb: "curb",
  // Disambiguate from a generic post.
  pole: "utility pole",
  // Distinguishable from the generic gloss, which drifts toward furniture.
  stairs: "staircase",

  // Overhead hazards, and the two prompts here that most need pinning: bare
  // "scaffolding" drifts toward interior shelving, and a bare "cable" embeds
  // as the object itself rather than one strung across a walkway at head
  // height — which is the only reason this class exists.
  scaffolding: "construction scaffolding",
  cable: "low hanging cable",
};

const objects = PHRASES.filter((p) => p.kind === "object");

if (objects.length === 0) {
  console.error("No object phrases in phrases.ts — nothing to export.");
  process.exit(1);
}

const lines = objects.map((p) => `${p.id} = ${PROMPT_OVERRIDES[p.id] ?? p.en}`);

const header = [
  "# Generated by scripts/export-classes.ts — do not edit by hand.",
  "# Line order IS the ONNX class index order. Regenerate after touching phrases.ts.",
  `# ${objects.length} classes.`,
  "",
].join("\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${header}${lines.join("\n")}\n`, "utf8");

const overridden = objects.filter((p) => PROMPT_OVERRIDES[p.id]).length;
console.log(`${OUT}\n${objects.length} classes, ${overridden} with prompt overrides.`);
